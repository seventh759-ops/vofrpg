from common_body import *
def rogue(kind):
    """影刃の系統。kind: base / night / eclipse / blood / bloodking"""
    c=C(96,136,10)
    blood = kind in ('blood','bloodking')
    # 外套（背中から裾まで、右へ少しなびく）
    c.poly([(33,26),(59,26),(70,100),(64,108),(28,108),(22,100)],'k')
    # 胴着・ズボン・靴
    c.poly([(37,30),(55,30),(58,64),(34,64)],'n')
    c.ell(46,32,12,5,'n')
    c.poly([(35,64),(57,64),(59,108),(48,108),(46,76),(44,108),(33,108)],'T')
    boots(c,104)
    c.rect(32,103,44,106,'g',only='b'); c.rect(48,103,60,106,'g',only='b')
    # 帯・留め金・短剣の鞘
    c.poly([(34,60),(58,60),(58,64),(34,64)],'b'); c.rect(43,59,49,65,'g'); c.rect(45,61,47,63,'b')
    c.poly([(36,62),(39,62),(33,80),(30,79)],'b')
    # 胸の革の当て
    c.poly([(39,38),(53,38),(52,52),(40,52)],'b'); c.line(46,38,46,52,'g')
    # 左腕：逆手に短剣
    c.poly([(36,31),(41,35),(38,62),(30,64),(30,46)],'n')
    c.rect(29,60,38,64,'b'); hand(c,33,67)
    c.line(33,70,31,84,'m',2) if not (kind in ('night','eclipse')) else c.line(33,70,29,86,'p',2)
    c.rect(30,68,36,69,'g')
    # 右腕：剣を下げて持つ
    c.poly([(56,31),(61,34),(66,58),(60,62),(56,46)],'n')
    c.rect(58,58,66,62,'b'); hand(c,63,65)
    c.rect(58,63,68,65,'g')
    if kind=='base':
        c.poly([(62,66),(65,66),(76,108),(73,110)],'m'); c.line(63,67,74,108,'x',1,only='m')
    elif kind in ('night','eclipse'):
        c.poly([(62,66),(66,66),(80,104),(76,108)],'p'); c.poly([(60,66),(62,66),(70,100),(68,101)],'p')
    else:
        big = kind=='bloodking'
        c.poly([(61,66),(67,66),(84 if big else 80,112),(78 if big else 75,116)],'R')
        c.line(63,68,78,110,'o',1,only='R')
    # 首巻き（なびく）
    sc = 'r'
    c.poly([(38,25),(54,25),(56,31),(36,31)],sc)
    c.poly([(36,27),(39,31),(20,40),(6,38),(18,33)],sc)
    c.poly([(20,40),(6,38),(2,44),(14,44)],sc)
    neck(c,'s')
    c.poly([(38,25),(54,25),(56,31),(36,31)],sc)
    # 頭巾 or 髪
    if blood:
        face(c,eye='R' if kind=='bloodking' else 'e',hair='x')
        # とがった白い髪
        c.poly([(36,12),(38,4),(41,7),(44,1),(47,5),(50,0),(53,6),(56,3),(56,13),(52,9),(48,12),(44,8),(40,12)],'x')
        c.poly([(36,10),(39,10),(38,21),(36,19)],'x'); c.poly([(53,10),(56,10),(56,19),(54,21)],'x')
        if kind=='bloodking':
            c.poly([(38,0),(54,0),(54,-3),(51,-1),(49,-6),(46,-2),(43,-6),(41,-1),(38,-3)],'g')
            c.set(46,-2,'R')
    else:
        c.ell(46,14,12,13,'n' if kind=='base' else 'k')
        face(c,eye='p' if kind=='eclipse' else 'e')
        c.ell(46,13,11,11.5,'n' if kind=='base' else 'k',only='.nk')
        if kind in ('night','eclipse'):
            c.poly([(36,6),(32,-4),(40,3)],'k'); c.poly([(56,6),(60,-4),(52,3)],'k')
        # 頭巾の影（顔の上）
        c.poly([(38,8),(54,8),(55,11),(37,11)],'k' if kind=='base' else 'n',only='s')
    # 外套のひだ
    for (x0,y0,x1,y1) in [(26,70,24,100),(66,70,68,100)]:
        c.line(x0,y0,x1,y1,'n',1,only='k')
    if kind=='eclipse':
        for (x,y) in [(14,60),(82,40),(10,90),(86,92)]: sparkle(c,x,y,'p',2)
    if kind=='bloodking':
        for (x,y) in [(12,62),(84,38),(14,96)]: sparkle(c,x,y,'R',2)
    return c
