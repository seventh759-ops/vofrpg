def vivid_hd():
    """彩灯者（細かい版）。参考画像に合わせる：
    白い頭巾がそのまま肩から裾まで広がる外套になり（外は白、内は紫、裾に渦の飾り）、額に金の冠と青い石、
    銀のまっすぐな長い髪、左右で色の違う目（赤と紫）、青と金の高い襟、彩りの石をはめた金の胸当て、
    青と金の肩当て、前の開いた白い長い上着（金のふち）、白いズボン、金のひざ当ての白い長靴。"""
    c=C(192,272)
    # ---- 外套（後ろ）：肩から裾へ大きく広がる。内側の紫が、上着と外の白の間に見える ----
    c.poly([(54,90),(114,90),(150,236),(140,250),(84,244),(28,250),(18,236)],'v')
    # 外の白：左右の前のふち（肩から裾へ、外へ広がる帯）
    c.poly([(50,92),(60,94),(42,250),(28,250),(18,236)],'C')
    c.poly([(118,92),(108,94),(126,250),(140,250),(150,236)],'C')
    # 裾の渦の飾り（白い布に紫の渦）
    for sx in (-1,1):
        bx=84+sx*58
        c.ell(bx,240,5,4,'v',only='C'); c.ell(bx+sx*2,239,2.5,2,'C',only='v')
        c.ell(bx-sx*6,244,3,2.5,'v',only='C')
    # ---- 脚：白いズボンと長靴、金のひざ当て・足首の金具 ----
    legs_hd(c,pants='T',boots='b',trim='g',top=150)
    for (x0,x1) in ((60,80),(90,110)):
        m=(x0+x1)/2
        c.poly([(x0,214),(m,204),(x1,214),(x1,224),(m,230),(x0,224)],'g')     # ひざ当て
    c.rect(56,252,79,256,'g'); c.rect(91,252,112,256,'g')                       # 足首の金具
    # ---- 上着：前の開いた白い長い上着（ひざの上まで）、金のふち ----
    c.poly([(60,94),(108,94),(102,138),(112,170),(118,214),(50,214),(56,170),(66,138)],'x')
    c.poly([(84,150),(98,214),(70,214)],'T')                                   # 前の開き（中のズボン）
    c.line(84,150,70,214,'g',1.4); c.line(84,150,98,214,'g',1.4)
    c.line(50,213,70,213,'g',1.6); c.line(98,213,118,213,'g',1.6)              # 裾のふち
    c.line(60,96,66,138,'g',1.1); c.line(108,96,102,138,'g',1.1)
    c.line(66,138,52,212,'g',1.1); c.line(102,138,116,212,'g',1.1)
    c.rect(66,138,102,141,'g')                                                 # 腰のふち
    c.poly([(58,200),(64,194),(66,206)],'g'); c.poly([(110,200),(104,194),(102,206)],'g')   # 裾の金の飾り
    # ---- 金の胸当て：彩りの石（中央に赤、まわりに紫・青・緑） ----
    c.poly([(68,100),(100,100),(102,116),(92,130),(84,140),(76,130),(66,116)],'g')
    c.line(70,103,98,103,'n',1); c.line(84,132,84,139,'n',1)                     # 胸当ての彫り
    c.ell(84,117,4,5,'R'); c.set(83,114,'o')                                                  # 中央の赤
    for (x,y,k) in [(76,108,'p'),(92,108,'W'),(73,114,'B'),(95,114,'B'),(79,124,'p'),(89,124,'p'),(84,108,'p')]:
        c.ell(x,y,2,2,k)
    c.poly([(80,134),(88,134),(84,146)],'g')                                   # 下の飾り
    # ---- 腕：両方とも下ろす。袖は上着と同じ白、手首の金と青の飾り ----
    arm_down(c,-1,'X',cuff=None)
    arm_down(c,1,'X',cuff=None)
    for ax in (54,114):
        c.poly([(ax-6,150),(ax,144),(ax+6,150),(ax,158)],'g'); c.ell(ax,150,1.6,1.8,'B')
        c.rect(ax-6,160,ax+6,163,'g')
    # ---- 肩当て：青に金のふち ----
    for sx in (-1,1):
        x0=84+sx*16; x1=84+sx*38
        c.poly([(x0,92),(x1,94),(x1+sx*2,104),(x0,100)],'n')
        c.line(x0,92,x1,94,'g',1.2); c.line(x1+sx*2,104,x0,100,'g',1.2)
    # ---- 胸の前に垂れる銀の髪（肩の上） ----
    c.poly([(66,80),(73,80),(72,118),(66,124),(62,104)],'q')
    c.poly([(95,80),(102,80),(106,104),(102,124),(96,118)],'q')
    # ---- 首と、青と金の高い襟（前に青い石） ----
    neck_hd(c)
    c.poly([(74,84),(94,84),(98,96),(70,96)],'n')
    c.poly([(80,88),(88,88),(86,98),(82,98)],'x')                              # 襟の合わせ目
    c.line(74,84,94,84,'g',1); c.line(70,96,98,96,'g',1.2)
    c.poly([(84,86),(87,90),(84,94),(81,90)],'g'); c.set(84,90,'B')
    # ---- 頭：頭巾は外套と同じ白（内側は紫の影）、額に金の冠と青い石 ----
    c.oy=10
    c.ox=2; face_hd(c); c.ox=0   # 顔は少し右（奥）へ向ける
    hood_hd(c,'C',inner='O')
    # まっすぐな銀の前髪（真ん中で分けて、顔の横へ）
    c.poly([(70,38),(98,38),(100,50),(94,44),(86,48),(84,42),(82,48),(74,44),(70,52)],'q')
    c.poly([(68,42),(73,42),(73,74),(69,78),(66,62)],'q'); c.poly([(98,42),(102,42),(103,62),(101,78),(98,74)],'q')   # 奥の髪は細く見える
    # 金の冠（額の上に山形、中央に青い石、額に小さな青い石）
    c.line(68,38,100,38,'g',2.2)
    c.ox=2   # 冠の山と額の石も、顔の向きに合わせて右へ
    c.poly([(78,37),(84,28),(90,37)],'g'); c.poly([(82,34),(84,30),(86,34),(84,37)],'B')
    for x in (73,95): c.poly([(x-3,37),(x,33),(x+3,37)],'g')
    c.ell(84,44,1.3,1.6,'B')
    c.ox=0
    # 左右で色の違う目（見て左が赤、右が紫）
    c.ox=3   # 顔を少し右へ向ける：目・鼻・口を右へ寄せる
    eyes_hd(c,iris='r',brow='q')
    for y in range(56,60):
        for x in range(87,94):
            if c.get(x,y)=='r': c.set(x,y,'p')
    c.ox=0
    c.oy=0
    turn(c)
    for (x,y,k) in [(24,60,'2'),(166,64,'3'),(12,170,'4'),(170,200,'5'),(30,26,'1')]: c.line(x-3,y,x+3,y,k); c.line(x,y-3,x,y+3,k)
    return c

def turn(c,near=1.06,far=0.84):
    """少し斜めに向けた立ち姿：見て左（手前）の半身を少し広く、右（奥）の半身を狭く描き直す。"""
    out=[]
    for row in c.g:
        new=['.']*c.w
        for x in range(c.w):
            k=near if x<CX else far
            sx=int(round(CX+(x-CX)/k))
            if 0<=sx<c.w: new[x]=row[sx]
        out.append(new)
    c.g=out
