from hd_body import *
def vivid_hd():
    """彩灯者（細かい版）。ダンジョンの絵に合わせる：白い頭巾と銀の髪、左右で色の違う目、白い上着と胸の彩りの石、淡い紫の長い外套、白い長靴、右手のひらに彩りの灯り。"""
    c=C(192,272)
    # 外套：淡い紫（ダンジョンの絵と同じ色。桃色はやめる）
    c.poly([(56,88),(112,88),(134,262),(34,262)],'v')
    # 長い髪（頭巾から背中へ）
    c.poly([(60,96),(108,96),(110,140),(98,150),(84,136),(70,150),(58,140)],'q')   # 首と服の間には出さない（肩の後ろから下だけ）
    legs_hd(c,pants='T',boots='b',trim='g')   # 長靴は白（ダンジョンの絵に合わせる）
    # 白い上着（ひざ丈）
    c.poly([(60,94),(108,94),(102,136),(110,164),(114,196),(54,196),(58,164),(66,136)],'x')   # 胴は広く、腰で細く、すそへ広がる
    c.rect(54,192,114,196,'g'); c.line(84,110,84,196,'g',1.2)
    c.line(62,96,66,136,'g',1.2); c.line(66,136,56,192,'g',1.2); c.line(106,96,102,136,'g',1.2); c.line(102,136,112,192,'g',1.2)
    for y in range(150,190,10):
        for dx in (-10,10): c.ell(84+dx,y,2,3,'u')                            # 淡い青の刺繍
    for (x0,x1) in ((58,44),(110,124),(64,58),(104,112)): c.line(x0,100,x1,256,'P' if False else 'u',1,only='v')
    c.rect(66,136,102,140,'g')
    # 胸の飾り：彩りの宝石を集めた留め具（ダンジョンの絵の胸の色石）
    c.rect(77,113,91,127,'g')
    for (x,y,k) in [(79,115,'R'),(83,115,'p'),(87,115,'B'),(79,119,'L'),(83,119,'o'),(87,119,'W'),(79,123,'p'),(83,123,'B'),(87,123,'R')]: c.rect(x,y,x+2,y+2,k)
    # 腕：左は下ろし、右は前へ手のひらを上に
    arm_down(c,-1,'X',cuff='g')                                                # 袖は上着と別の素材（境目に影）
    c.poly([(100,94),(114,90),(118,116),(136,146),(130,156),(106,132)],'X')
    c.rect(124,142,134,154,'g')
    c.ell(140,150,7,5,'s')
    c.ell(140,138,4,4,'p'); c.ell(140,138,2,2,'o')
    for (x,y,k) in [(150,124,'2'),(130,120,'3'),(156,140,'4'),(146,112,'5')]: c.line(x-2,y,x+2,y,k); c.line(x,y-2,x,y+2,k)
    neck_hd(c)
    c.ell(84,92,15,5,'x'); c.line(71,89,97,89,'g',1)   # 上着の丸い襟（首の下にすき間を作らない）
    c.oy=10   # 頭を下げて首を短く（頭巾のふくらみで首の横を隠す）
    face_hd(c)
    # 白い頭巾：上は丸く、顔のまわりを包み、あごの横から肩へ布がたまる（ダンジョンの絵と同じ白い頭巾）
    hood_hd(c,'x',inner='O')
    # 頭巾の中の銀の前髪（横へ流す）と、顔の横に垂れる髪
    c.poly([(70,38),(98,38),(100,48),(92,43),(85,49),(78,44),(71,51)],'q')
    c.poly([(68,42),(73,42),(73,70),(69,74),(66,60)],'q'); c.poly([(95,42),(100,42),(102,60),(99,74),(95,70)],'q')
    # 額の小さな飾り（頭巾のふちに、彩りの石）
    c.ell(84,31,2.5,2.5,'g'); c.set(84,31,'p')
    # 左右で色の違う目（見て左が赤、右が青）
    eyes_hd(c,iris='r',brow='q')
    for y in range(56,60):
        for x in range(87,94):
            if c.get(x,y)=='r': c.set(x,y,'B')
    c.oy=0
    for (x,y,k) in [(24,60,'2'),(168,70,'3'),(20,180,'4'),(170,220,'5'),(36,30,'1')]: c.line(x-3,y,x+3,y,k); c.line(x,y-3,x,y+3,k)
    return c
