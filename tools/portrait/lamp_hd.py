    for ex,side in ((78,-1),(91,1)):
        c.rect(ex-3,56,ex+3,59,'x')
        c.rect(ex-2,56,ex+1,59,'I'); c.rect(ex-1,57,ex,59,'e'); c.set(ex+1,56,'x')
