    """灯術師（細かい版・192×272）。見本の絵に合わせた細身の約7頭身：
    とがった頭巾と肩を覆う頭巾の肩掛け（金の縁）、金の立ち襟、体に沿う胴と足首までの長衣、
    二重に巻いた縄の帯と房・小袋、ひじから広がる袖（金の模様の袖口）、長靴、鉄の飾りランタンの杖（青白く光る結晶）。"""
    c=C(192,272)
    CX=84
    # ---- 杖とランタン（体の後ろ） ----
    c.rect(147,70,153,260,'i')                                            # 杖は上から下まで同じ太さ（7ドット）
    c.poly([(147,260),(153,260),(150,270)],'i')
    for y in (74,186): c.rect(146,y,154,y+2,'i')
    for k in range(6): c.line(147,96+k*5,153,99+k*5,'g',1)            # 握りのらせんの飾り
    c.poly([(144,64),(156,64),(153,74),(147,74)],'i'); c.ell(150,76,2.5,2.5,'g')
    if kind in ('base','flare','pyre'):
        # 吊り手の鉤と丸い屋根・先の飾り玉
        for a_ in range(180,361,6):
            r=math.radians(a_); c.ell(150+6*math.cos(r),6+6*math.sin(r),1.1,1.1,'i')
        c.line(156,6,156,10,'i',2)
