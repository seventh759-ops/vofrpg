def hair_bob(c,col):
    """肩の上までの短い髪（灯番）。"""
    c.ell(CX,46,17,15,col,only='.')
    c.poly([(66,44),(102,44),(104,76),(96,80),(98,60),(70,60),(72,80),(64,76)],col,only='.')
