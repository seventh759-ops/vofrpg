    c.line(45,21,46,21,'K')
    # 額の飾り
    c.ell(46,7,1.6,1.6,'g'); c.set(46,7,'p')
    for (x,y,col) in [(12,40,'p'),(82,30,'B'),(10,96,'W'),(86,90,'L')]: sparkle(c,x,y,col,2)
    return c
