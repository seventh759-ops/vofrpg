    c.poly([(56,34),(61,38),(66,64),(60,68),(56,50)],'x'); c.rect(58,64,67,68,'g'); hand(c,63,72)
    c.ell(64,64,2.2,2.2,'p'); c.set(64,64,'o')   # 手のひらに浮かぶ彩りの灯り
    neck(c)
    # 顔と髪（銀）：頭の後ろの髪、前髪、肩へ垂れる横の髪
    c.ell(46,13,11,11,'q',only='.')
    face(c,eye='e',hair='q',hl=None)
    c.rect(42,16,43,18,'p'); c.rect(49,16,50,18,'B')       # 左右で色の違う目
