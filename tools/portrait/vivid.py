def vivid():
    """彩灯者：銀の長い髪、白い上着、淡い紫の長い外套、淡い青の肩掛け、胸に彩りの宝石。"""
    c=C(96,136,10)
    # 長い外套（後ろに広がる）
    c.poly([(30,26),(62,26),(76,116),(16,116)],'v')
    # 長い髪（背中へ）
    c.poly([(34,10),(58,10),(62,64),(54,70),(46,60),(38,70),(30,64)],'q')
    # 上着・ズボン・長靴
    c.poly([(36,30),(56,30),(60,84),(32,84)],'x')
    c.ell(46,32,12,5,'x')
    c.poly([(35,84),(57,84),(57,104),(48,104),(46,90),(44,104),(35,104)],'T')
    boots(c,100)
    # 肩掛け
    c.poly([(30,28),(62,28),(64,44),(46,52),(28,44)],'u')
    c.line(28,44,46,52,'g',1.2); c.line(46,52,64,44,'g',1.2)
    # 胸の宝石（彩り）
    c.ell(46,56,3.5,4,'g'); c.set(45,55,'p'); c.set(47,55,'B'); c.set(45,57,'W'); c.set(47,57,'L'); c.set(46,56,'o')
    # 帯と金の縁
    c.poly([(34,70),(58,70),(58,73),(34,73)],'g')
    c.line(46,52,46,84,'g',1)
